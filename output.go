package main

import (
	"fmt"
	"strings"
)

// renderScript formats the voice-acting script for one mission.
func renderScript(m *mission, entries []entry) string {
	var b strings.Builder
	fmt.Fprintf(&b, "# Voice script — %s\n", m.File)
	fmt.Fprintf(&b, "# generated by fs2voice\n\n")

	// Section headers are only worth printing when briefings are present;
	// otherwise the script is just mission messages, as before.
	hasBriefings := false
	for _, e := range entries {
		if e.Section != secMessages {
			hasBriefings = true
			break
		}
	}

	inOrphans := false
	section := "-" // no section yet
	for i, e := range entries {
		if e.Orphan && !inOrphans {
			b.WriteString("\n--- ORPHANS (in #Messages, not referenced by any #Events) ---\n\n")
			inOrphans = true
		}
		if !e.Orphan && hasBriefings && e.Section != section {
			if i > 0 {
				b.WriteByte('\n')
			}
			fmt.Fprintf(&b, "--- %s ---\n\n", sectionTitles[e.Section])
			section = e.Section
		}
		writeEntry(&b, e)
		b.WriteByte('\n')
	}
	return b.String()
}

func writeEntry(b *strings.Builder, e entry) {
	sender := e.Sender
	if sender == "" {
		sender = "—"
	}
	fmt.Fprintf(b, "Sender:   %s\n", sender)
	if e.Persona != "" && !strings.EqualFold(e.Persona, e.Sender) {
		fmt.Fprintf(b, "Persona:  %s\n", e.Persona)
	}
	fmt.Fprintf(b, "Message:  %s\n", e.Text)
	fmt.Fprintf(b, "Filename: %s\n", e.Filename)
	if e.MsgName != "" {
		fmt.Fprintf(b, "Ref:      %s\n", e.MsgName)
	}
	if e.Note != "" {
		fmt.Fprintf(b, "Note:     %s\n", e.Note)
	}
}
